"""Rows killed by C20 (Eisenstein characters on a quotient of exponent 3), written as Lean.

`eisensteinchars.py`: for each open row of instances.csv minus the IDs in scratch/settle-round2.tsv
and those in GaussCharsRows.lean, tries the quotients C₃^a (dᵢ ∈ {1, 3}, dᵢ | mᵢ, a ≤ 4) and keeps
the first that passes Lean's `EisKills`; writes lean/SignedDifferenceSets/EisensteinCharsRows.lean.
Standard library only; mirrors `sqrtUp`, `eisBound`, `eisTracesNat`, `eisTraces`, `reachMod`
and `EisKills` exactly.
"""
import csv
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "EisensteinCharsRows.lean"
SETTLED = ROOT / "scratch" / "settle-round2.tsv"
GAUSS_ROWS = ROOT / "lean" / "SignedDifferenceSets" / "GaussCharsRows.lean"
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
GAUSS_ID = re.compile(r"\(⟨(\d+),")
OPEN = "open"
MAX_A = 4
CHUNK = 60


def sqrt_up(n, f, i):
    for _ in range(f):
        if n <= i * i:
            return i
        i += 1
    return n


def eis_bound(n):
    return sqrt_up(4 * n, 4 * n + 1, 0)


def eis_traces_nat(n):
    M = eis_bound(n)
    return [t for t in range(M + 1) if any(t * t + 3 * (b * b) == 4 * n for b in range(M + 1))]


def eis_traces(n):
    return [x for t in eis_traces_nat(max(n, 0)) for x in (t, -t)]


def reach(N, A, a, S):
    for _ in range(a):
        S = {(r + x) % N for r in S for x in A}
    return S


def eis_kills(N, s, n):
    T = eis_traces(n)
    return all(0 not in reach(N, T, (N - 1) // 2, {sp % N}) for sp in (s, -s))


def cert(v, k, lam, ms):
    n, S = k - lam, k + lam * (v - 1)
    if S < 0 or math.isqrt(S) ** 2 != S:
        return None
    s = math.isqrt(S)
    threes = [i for i, x in enumerate(ms) if x % 3 == 0]
    for a in range(1, min(len(threes), MAX_A) + 1):
        ds = [3 if i in threes[:a] else 1 for i in range(len(ms))]
        if eis_kills(3 ** a, s, n):
            return ds, s
    return None


def main():
    skip = {l.split("\t")[0] for l in open(SETTLED, encoding="utf-8") if l.strip()}
    skip |= {f"N{x}" for x in GAUSS_ID.findall(GAUSS_ROWS.read_text(encoding="utf-8"))}
    entries = []
    for r in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if r["status"] != OPEN or r["id"] in skip:
            continue
        mm = KEY.fullmatch(r["key"])
        v, k, lam = map(int, mm.groups()[:3])
        ms = [int(x) for x in mm.group(4).split(",")]
        c = cert(v, k, lam, ms)
        if c:
            ds, s = c
            entries.append(f"  (⟨{r['id'][1:]}, [{', '.join(map(str, ms))}], {k}, {lam}⟩, "
                           f"⟨[{', '.join(map(str, ds))}], {s}⟩)")
    chunks = []
    for i in range(0, len(entries), CHUNK):
        j = i // CHUNK + 1
        body = ",\n".join(entries[i: i + CHUNK])
        chunks.append(f"""/-- Rows and certificates, chunk {j}. -/
def eisensteinCharsRows{j} : List (Row × EcCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem eisensteinCharsRows{j}_kill : ∀ x ∈ eisensteinCharsRows{j}, x.2.Kills x.1 := by
  decide +kernel

/-- No row of chunk {j} has an SDS. -/
theorem eisensteinCharsRows{j}_not_hasSDS {{x : Row × EcCert}} (hx : x ∈ eisensteinCharsRows{j})
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  EcCert.not_hasSDS (eisensteinCharsRows{j}_kill x hx) inst
""")
    OUT.write_text(f"""module

public import SignedDifferenceSets.EisensteinChars
public import SignedDifferenceSets.SelfConjugacyCheck

/-!
# Rows killed by C20

A certificate is a quotient `Grp ds` with every `dᵢ ∣ 3` (so `3h = 0`) and the sign sum `s`
(C1); `EcCert.Kills` checks it and `EisKills`. {len(entries)} open rows, generated by
`solver/eisensteinchars.py`, checked in chunks of {CHUNK}, one `decide +kernel` each.
-/

@[expose] public section

namespace SignedDifferenceSets

/-- A C20 certificate: the quotient and the sign sum. -/
structure EcCert where
  ds : List ℕ
  s : ℤ
  deriving DecidableEq

/-- The row's arithmetic and C20's kill condition on `Grp ds`. -/
def EcCert.Kills (r : Row) (c : EcCert) : Prop :=
  (∀ m ∈ r.ms, 0 < m) ∧ Dvds c.ds r.ms ∧ (∀ d ∈ c.ds, d ∣ 3) ∧
    c.s ^ 2 = r.k + r.lam * ((r.ms.prod : ℤ) - 1) ∧ EisKills c.ds.prod c.s (r.k - r.lam)

instance EcCert.instDecidableKills (r : Row) (c : EcCert) : Decidable (c.Kills r) := by
  unfold EcCert.Kills; infer_instance

/-- A row C20 kills has no SDS, whatever `Fintype` instance its group carries. -/
theorem EcCert.not_hasSDS {{r : Row}} {{c : EcCert}} (h : c.Kills r) (inst : Fintype (Grp r.ms)) :
    ¬ @HasSDS (Grp r.ms) _ inst r.k r.lam := by
  obtain ⟨hms, hdv, h3, hs, hk⟩ := h
  let _ : Fintype (Grp c.ds) := Grp.fintype c.ds (Dvds.pos _ _ hdv hms)
  refine not_hasSDS_of_eisensteinChars (quot_surjective r.ms c.ds hdv)
    (fun x => Grp.nsmul_eq_zero c.ds h3 x) (s := c.s) ?_ ?_
  · rw [hs, Grp.card_eq]
  · rwa [Grp.card_eq]

{chr(10).join(chunks)}
end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
    print(len(entries), "rows")


if __name__ == "__main__":
    main()
