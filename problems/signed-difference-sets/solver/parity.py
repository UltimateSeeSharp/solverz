"""Rows killed by C8 (support parity), written as Lean.

`parity.py`: lists the open rows of instances.csv with v odd, λ even and d(d − 1) < v − 1
(d = v − k) in lean/SignedDifferenceSets/ParityRows.lean, checked there by `decide +kernel`.
Standard library only.
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "ParityRows.lean"
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
OPEN = "open"


def kills(v, k, lam):
    d = max(v - k, 0)
    return v % 2 == 1 and lam % 2 == 0 and d * max(d - 1, 0) < v - 1


rows = []
for r in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
    if r["status"] != OPEN:
        continue
    m = KEY.fullmatch(r["key"])
    v, k, lam = map(int, m.groups()[:3])
    if kills(v, k, lam):
        rows.append(f"  ⟨{r['id'][1:]}, [{m.group(4).replace(',', ', ')}], {k}, {lam}⟩")
body = ",\n".join(rows)
OUT.write_text(f"""module

public import SignedDifferenceSets.Parity
public import SignedDifferenceSets.SelfConjugacyCheck

/-!
# Rows killed by C8 (support parity)

{len(rows)} open rows with `v` odd, `λ` even and `d(d − 1) < v − 1` (generated by
`solver/parity.py`); `parityRows_kill` checks every one by `decide +kernel`.
-/

@[expose] public section

namespace SignedDifferenceSets.ParityRows

/-- The rows. -/
def parityRows : List Row := [
{body}]

set_option maxRecDepth 100000 in
theorem parityRows_kill : ∀ x ∈ parityRows, SupportParity x.ms.prod x.k x.lam := by
  decide +kernel

/-- No row of `parityRows` has an SDS. -/
theorem parityRows_not_hasSDS {{x : Row}} (hx : x ∈ parityRows) (inst : Fintype (Grp x.ms)) :
    ¬ @HasSDS (Grp x.ms) _ inst x.k x.lam :=
  not_hasSDS_of_supportParity (Grp.card_eq x.ms) (parityRows_kill x hx)

end SignedDifferenceSets.ParityRows
""", encoding="utf-8", newline="\n")
print(len(rows), "rows")
