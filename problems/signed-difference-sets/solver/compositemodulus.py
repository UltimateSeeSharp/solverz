"""Rows killed by C23 (C5's congruences for two or more primes, C14's box test mod their product),
written as Lean.

`compositemodulus.py`: for each open row of instances.csv, tries the quotients `Grp ds` (dᵢ ∣ mᵢ) in
order of size; S = the primes p ∣ n with p² ∣ n, p ∤ |H| and p self-conjugate mod exp H (each with
i = least, j = ⌊v_p(n)/2⌋), at least two of them; q = ∏ p^j ≤ MAX_Q; keeps the first quotient where
both signs and every residue fail `box_ok`. Writes lean/SignedDifferenceSets/CompositeModulusRows.lean
(one `decide +kernel` per chunk). Standard library only; mirrors `CmCert.Kills`.
"""
import csv
import itertools
import math
from pathlib import Path

from selfconj import KEY, OPEN, box_ok, conj_exp, divisors, primes_of

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "CompositeModulusRows.lean"
MAX_Q = 5000
CHUNK = 40


def vp(x, p):
    e = 0
    while x % p == 0:
        x //= p
        e += 1
    return e


def cert(v, k, lam, ms):
    n = k - lam
    S = k + lam * (v - 1)
    if n == 0 or S < 0 or math.isqrt(S) ** 2 != S:
        return None
    s = math.isqrt(S)
    seen = set()
    for ds in sorted(itertools.product(*[divisors(m) for m in ms]), key=math.prod):
        h, e = math.prod(ds), math.lcm(*ds)
        if h == 1 or (h, e) in seen:
            continue
        seen.add((h, e))
        ps = [(p, conj_exp(p, e), vp(abs(n), p) // 2) for p in primes_of(abs(n))
              if h % p and vp(abs(n), p) >= 2 and conj_exp(p, e) is not None]
        if len(ps) < 2:
            continue
        q = math.prod(p ** j for p, _, j in ps)
        if q > MAX_Q:
            continue
        c, Q = v // h, k + lam * (v // h - 1)
        if not any(box_ok(h, q, sp, Q, t, c) for sp in (s, -s) for t in range(q)):
            return list(ds), ps, s
    return None


def main():
    entries = []
    for r in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if r["status"] != OPEN:
            continue
        mm = KEY.fullmatch(r["key"])
        v, k, lam = map(int, mm.groups()[:3])
        ms = [int(x) for x in mm.group(4).split(",")]
        c = cert(v, k, lam, ms)
        if c:
            ds, ps, s = c
            lam_lean = f"({lam})" if lam < 0 else str(lam)
            pl = ", ".join(f"({p}, {i}, {j})" for p, i, j in ps)
            entries.append(f"  (⟨{r['id'][1:]}, [{', '.join(map(str, ms))}], {k}, {lam_lean}⟩,\n"
                           f"    ⟨[{', '.join(map(str, ds))}], [{pl}], {s}⟩)")
    chunks = []
    for i in range(0, len(entries), CHUNK):
        j = i // CHUNK + 1
        body = ",\n".join(entries[i: i + CHUNK])
        chunks.append(f"""/-- Rows and certificates, chunk {j}. -/
def compositeModulusRows{j} : List (Row × CmCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem compositeModulusRows{j}_kill : ∀ x ∈ compositeModulusRows{j}, x.2.Kills x.1 := by
  decide +kernel

/-- No row of chunk {j} has an SDS. -/
theorem compositeModulusRows{j}_not_hasSDS {{x : Row × CmCert}}
    (hx : x ∈ compositeModulusRows{j}) (inst : Fintype (Grp x.1.ms)) :
    ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  CmCert.not_hasSDS (compositeModulusRows{j}_kill x hx) inst
""")
    OUT.write_text(f"""module

public import SignedDifferenceSets.CompositeModulus

/-!
# Rows killed by C23

{len(entries)} open rows, each with a quotient `Grp ds`, primes `(p, i, j)` and the sign sum `s`,
checked by `CmCert.Kills` in chunks of {CHUNK}, one `decide +kernel` each; generated by
`solver/compositemodulus.py`.
-/

@[expose] public section

namespace SignedDifferenceSets

{chr(10).join(chunks)}
end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
    print(len(entries), "rows")


if __name__ == "__main__":
    main()
