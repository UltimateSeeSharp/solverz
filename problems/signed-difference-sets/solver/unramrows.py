"""C27 rows: open rows killed by field descent without ramification (`UnramifiedDescent.lean`).

For each open row, the first cyclic quotient C_m (m | exp G, gcd(m, n) = 1) and F (rad m | F | m) with every
1 + F u (u < m/F) a power of each prime p | n mod m and m F c^2 < phi(m) n, c = v/m. Writes
`lean/SignedDifferenceSets/UnramifiedRows.lean` (chunks of CHUNK rows) and `scratch/settle-c27.tsv`.
Run from the problem folder: python solver/unramrows.py
"""

import csv
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lean" / "SignedDifferenceSets" / "UnramifiedRows.lean"
TSV = ROOT / "scratch" / "settle-c27.tsv"
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
CHUNK = 60
OPEN = "open"
NL = "\n"


def primes(n):
    out, d = [], 2
    while d * d <= n:
        if n % d == 0:
            out.append(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        out.append(n)
    return out


def phi(m):
    r = m
    for p in primes(m):
        r = r // p * (p - 1)
    return r


def powers(p, m):
    out, x = set(), 1 % m
    while x not in out:
        out.add(x)
        x = x * p % m
    return out


def form(ms, m):
    """Coefficients A of a surjective form Grp ms -> ZMod m and a preimage P of 1 (CRT)."""
    g = [1] * len(ms)
    for p in primes(m):
        q = p ** next(e for e in range(64, 0, -1) if m % p ** e == 0)
        i = next(i for i, x in enumerate(ms) if x % q == 0)
        g[i] *= q
    A = [m // gi if gi > 1 else 0 for gi in g]
    P = [pow(m // gi, -1, gi) if gi > 1 else 0 for gi in g]
    assert all(a * x % m == 0 for a, x in zip(A, ms)), (ms, m, A)
    assert sum(a * x for a, x in zip(A, P)) % m == 1 % m, (ms, m, A, P)
    return A, P


def cert(v, k, lam, ms):
    """(m, F) killing the row, or None."""
    n = k - lam
    if n <= 1:
        return None
    w = math.lcm(*ms)
    ps = primes(n)
    for m in range(2, w + 1):
        if w % m or math.gcd(m, n) != 1:
            continue
        c = v // m
        M = set.intersection(*(powers(p, m) for p in ps))
        rad = math.prod(primes(m))
        for F in sorted(f for f in range(rad, m + 1, rad) if m % f == 0):
            if all((1 + F * u) % m in M for u in range(m // F)):
                if m * F * c * c < phi(m) * n:
                    return m, F
                break
    return None


def lst(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def main():
    rows = []
    for r in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if r["status"] != OPEN:
            continue
        v, k, lam, ms = KEY.fullmatch(r["key"]).groups()
        v, k, lam, ms = int(v), int(k), int(lam), [int(x) for x in ms.split(",")]
        hit = cert(v, k, lam, ms)
        if hit:
            m, F = hit
            A, P = form(ms, m)
            rows.append((r["id"], ms, k, lam, m, F, A, P))
    chunks = [rows[i: i + CHUNK] for i in range(0, len(rows), CHUNK)]
    blocks, tsv = [], []
    for num, chunk in enumerate(chunks, 1):
        body = ("," + NL).join(f"  (⟨{i[1:]}, {lst(ms)}, {k}, {lam}⟩, ⟨{m}, {F}, {lst(A)}, {lst(P)}⟩)"
                               for i, ms, k, lam, m, F, A, P in chunk)
        blocks.append(f"""/-- Rows and certificates, chunk {num}. -/
def unramifiedRows{num} : List (Row × DescentRowCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem unramifiedRows{num}_kill : ∀ x ∈ unramifiedRows{num}, x.2.Kills x.1 := by decide +kernel

/-- No row of `unramifiedRows{num}` has an SDS. -/
theorem unramifiedRows{num}_not_hasSDS {{x : Row × DescentRowCert}} (hx : x ∈ unramifiedRows{num})
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  DescentRowCert.not_hasSDS (unramifiedRows{num}_kill x hx) inst
""")
        tsv += [f"{i}\tnone\tC27; UnramifiedRows\tSignedDifferenceSets.unramifiedRows{num}_not_hasSDS"
                for i, *_ in chunk]
    OUT.write_text(f"""module

public import SignedDifferenceSets.UnramifiedDescent

/-!
# Rows killed by C27 (field descent without ramification)

{len(rows)} open rows, each with a cyclic quotient `ZMod m` (the form `A`, a preimage `P` of `1`) and
`F` such that `DescentRowCert.Kills` holds, in {len(chunks)} chunks checked by `decide +kernel`;
generated by `solver/unramrows.py`.
-/

@[expose] public section

namespace SignedDifferenceSets

{NL.join(blocks)}
end SignedDifferenceSets
""", encoding="utf-8", newline=NL)
    TSV.write_text("".join(t + NL for t in tsv), encoding="utf-8", newline=NL)
    print(len(rows), "rows in", len(chunks), "chunks")


if __name__ == "__main__":
    main()
