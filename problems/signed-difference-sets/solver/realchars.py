"""Rows killed by C17 (real characters on C₂^r), written as Lean.

`realchars.py`: lists each open row of instances.csv with k − λ = m², k + λ(v − 1) = s² and,
for r = R the number of even factors (the test only gets stronger with r), no s' = ±s and odd T
with |T| ≤ 2^r − 1 such that 2^r ∣ s' + mT; writes the rows with their certificates (r, s, m) to
lean/SignedDifferenceSets/RealCharsRows.lean, checked there by `decide +kernel`.
Standard library only.
"""
import csv
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "RealCharsRows.lean"
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
OPEN = "open"


def fires(r, s, m):
    """C17's condition: 2^r divides no s' + m(2j + 1 − 2^r), s' = ±s, 0 ≤ j < 2^r."""
    n = 1 << r
    return all((sp + m * (2 * j + 1 - n)) % n for sp in (s, -s) for j in range(n))


def cert(v, k, lam, ms):
    """(r, s, m) for the least r that fires, or None."""
    n, sq = k - lam, k + lam * (v - 1)
    if n < 0 or sq < 0:
        return None
    m, s = math.isqrt(n), math.isqrt(sq)
    if m * m != n or s * s != sq:
        return None
    r = sum(1 for x in ms if x % 2 == 0)
    return (r, s, m) if r > 0 and fires(r, s, m) else None


rows = []
for row in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
    if row["status"] != OPEN:
        continue
    g = KEY.fullmatch(row["key"])
    v, k, lam = map(int, g.groups()[:3])
    ms = [int(x) for x in g.group(4).split(",")]
    c = cert(v, k, lam, ms)
    if c:
        rows.append(f"  (⟨{row['id'][1:]}, [{', '.join(map(str, ms))}], {k}, {lam}⟩, "
                    f"⟨{c[0]}, {c[1]}, {c[2]}⟩)")
body = ",\n".join(rows)
OUT.write_text(f"""module

public import SignedDifferenceSets.RealChars
public import SignedDifferenceSets.SelfConjugacyCheck

/-!
# Rows killed by C17 (real characters)

A row dies by C17 with a certificate (`r`, `s`, `m`): the quotient `Grp (evenQuot ms r)` (`2` on
the first `r` even factors, `1` elsewhere) has order `2^r`, `s² = k + λ(v − 1)`, `m² = k − λ`,
and `2^r` divides no `s' + m T` for `s' = ±s` and odd `T = 2j + 1 − 2^r`, `j < 2^r`
(`RcCert.Kills`). {len(rows)} open rows (generated by `solver/realchars.py`);
`realCharsRows_kill` checks every one by `decide +kernel`.
-/

@[expose] public section

namespace SignedDifferenceSets

/-- `2` on the first `r` even factors of `ms`, `1` elsewhere. -/
def evenQuot : List ℕ → ℕ → List ℕ
  | [], _ => []
  | m :: ms, r => if 0 < r ∧ m % 2 = 0 then 2 :: evenQuot ms (r - 1) else 1 :: evenQuot ms r

/-- A certificate for C17: the number `r` of even factors used, `s` and `m`. -/
structure RcCert where
  r : ℕ
  s : ℤ
  m : ℤ
  deriving DecidableEq

/-- C17's hypotheses on a row, as arithmetic. -/
def RcCert.Kills (x : Row) (c : RcCert) : Prop :=
  (∀ m ∈ x.ms, 0 < m) ∧ Dvds (evenQuot x.ms c.r) x.ms ∧ (∀ d ∈ evenQuot x.ms c.r, d ∣ 2) ∧
    (evenQuot x.ms c.r).prod = 2 ^ c.r ∧ 0 < c.r ∧ c.m ^ 2 = x.k - x.lam ∧
    c.s ^ 2 = x.k + x.lam * ((x.ms.prod : ℤ) - 1) ∧
    ∀ s' ∈ [c.s, -c.s], ∀ j ∈ List.range (2 ^ c.r),
      ¬ (2 : ℤ) ^ c.r ∣ s' + c.m * (2 * j + 1 - 2 ^ c.r)

instance (x : Row) (c : RcCert) : Decidable (c.Kills x) := by
  unfold RcCert.Kills; infer_instance

/-- A killed row has no SDS, whatever `Fintype` instance its group carries. -/
theorem RcCert.not_hasSDS {{x : Row}} {{c : RcCert}} (h : c.Kills x) (inst : Fintype (Grp x.ms)) :
    ¬ @HasSDS (Grp x.ms) _ inst x.k x.lam := by
  obtain ⟨hms, hdv, hds, hprod, hr, hm, hs, hkill⟩ := h
  let _ : Fintype (Grp (evenQuot x.ms c.r)) := Grp.fintype _ (Dvds.pos _ _ hdv hms)
  refine not_hasSDS_of_realChars (quot_surjective _ _ hdv) (fun h => ?_) hr
    (by rw [Grp.card_eq, hprod]) hm (by rw [Grp.card_eq]; exact hs) ?_
  · have := Grp.nsmul_eq_zero (N := 2) _ hds h
    rwa [two_nsmul] at this
  · intro s' hs' T hT hTabs
    obtain ⟨t, rfl⟩ := hT
    rw [abs_le] at hTabs
    have hN : (2 : ℤ) ^ c.r = 2 * 2 ^ (c.r - 1) := by rw [← pow_succ', Nat.sub_add_cancel hr]
    have hcast : ((2 ^ c.r : ℕ) : ℤ) = 2 ^ c.r := by push_cast; rfl
    have hj0 : 0 ≤ t + 2 ^ (c.r - 1) := by omega
    have hj : (t + 2 ^ (c.r - 1)).toNat < 2 ^ c.r := by
      rw [← Nat.cast_lt (α := ℤ), Int.toNat_of_nonneg hj0, hcast]; omega
    have := hkill s' hs' _ (List.mem_range.2 hj)
    rwa [Int.toNat_of_nonneg hj0,
      show 2 * (t + 2 ^ (c.r - 1)) + 1 - 2 ^ c.r = 2 * t + 1 by omega] at this

/-- The rows and certificates. -/
def realCharsRows : List (Row × RcCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem realCharsRows_kill : ∀ x ∈ realCharsRows, x.2.Kills x.1 := by decide +kernel

/-- No row of `realCharsRows` has an SDS. -/
theorem realCharsRows_not_hasSDS {{x : Row × RcCert}} (hx : x ∈ realCharsRows)
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  RcCert.not_hasSDS (realCharsRows_kill x hx) inst

/-! Tests: the rule kills N4302; it fails on the existing N19 and N669 for every `r`. -/

/-- N4302 (136, 90, 26) in `C₂ × C₂ × C₃₄`: `s = 60`, `m = 8`, `r = 3`. -/
example : ¬ HasSDS (ZMod 2 × ZMod 2 × ZMod 34) 90 26 :=
  realCharsRows_not_hasSDS (x := (⟨4302, [2, 2, 34], 90, 26⟩, ⟨3, 60, 8⟩)) (by decide +kernel) _

/-- N19 (18, 13, 4) in `C₃ × C₆` exists: `s = 9`, `m = 3`. -/
example : ∀ r ∈ List.range 3, ¬ RcCert.Kills ⟨19, [3, 6], 13, 4⟩ ⟨r, 9, 3⟩ := by
  decide +kernel

/-- N669 (64, 22, 6) in `C₂⁶` exists: `s = 20`, `m = 4`. -/
example : ∀ r ∈ List.range 8, ¬ RcCert.Kills ⟨669, [2, 2, 2, 2, 2, 2], 22, 6⟩ ⟨r, 20, 4⟩ := by
  decide +kernel

end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
print(len(rows), "rows")
