"""Rows killed by C22's equality part at p = 2 (`not_hasSDS_of_sylow_two`), written as Lean.

`sylowtworows.py`: for each open row of instances.csv with v even, the Sylow 2-quotient `Grp ds`
(dᵢ = 2^v₂(mᵢ)), t = v₂(v), J = max v₂(mᵢ), r = 2^(J−1), n = k − λ = m², w = v₂(m); the row dies
when w < t and 2^(w+1) ∣ s. Writes lean/SignedDifferenceSets/SylowTwoRows.lean (one
`decide +kernel` per chunk). Standard library only; mirrors `SyTwoCert.Kills`.
"""
import csv
import math
from pathlib import Path

from sylowrows import KEY, OPEN, vp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "SylowTwoRows.lean"
CHUNK = 50
PAIRS = {(2, 2 ** a) for a in range(8)}


def cert(v, k, lam, ms):
    if v % 2:
        return None
    n, S = k - lam, k + lam * (v - 1)
    if n <= 0 or S < 0 or math.isqrt(n) ** 2 != n or math.isqrt(S) ** 2 != S:
        return None
    m, s = math.isqrt(n), math.isqrt(S)
    ds = [2 ** vp(x, 2) for x in ms]
    r = 2 ** (max(vp(x, 2) for x in ms) - 1)
    t, w = vp(v, 2), vp(m, 2)
    if w < t and s % 2 ** (w + 1) == 0 and (2, r) in PAIRS:
        return r, m, w, t, s, ds
    return None


def main():
    entries = []
    for row in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if row["status"] != OPEN:
            continue
        mm = KEY.fullmatch(row["key"])
        v, k, lam = map(int, mm.groups()[:3])
        ms = [int(x) for x in mm.group(4).split(",")]
        c = cert(v, k, lam, ms)
        if c:
            r, m, w, t, s, ds = c
            lam_lean = f"({lam})" if lam < 0 else str(lam)
            entries.append(f"  (⟨{row['id'][1:]}, [{', '.join(map(str, ms))}], {k}, {lam_lean}⟩,\n"
                           f"    ⟨{r}, {m}, {w}, {t}, {s}, [{', '.join(map(str, ds))}]⟩)")
    chunks = []
    for i in range(0, len(entries), CHUNK):
        j = i // CHUNK + 1
        body = ",\n".join(entries[i: i + CHUNK])
        chunks.append(f"""/-- Rows and certificates, chunk {j}. -/
def sylowTwoRows{j} : List (Row × SyTwoCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem sylowTwoRows{j}_kill : ∀ x ∈ sylowTwoRows{j}, x.2.Kills x.1 := by decide +kernel

/-- No row of chunk {j} has an SDS. -/
theorem sylowTwoRows{j}_not_hasSDS {{x : Row × SyTwoCert}} (hx : x ∈ sylowTwoRows{j})
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  SyTwoCert.not_hasSDS (sylowTwoRows{j}_kill x hx) inst
""")
    OUT.write_text(f"""module

public import SignedDifferenceSets.SylowTwo

/-!
# Rows killed by C22's equality part at `p = 2`

{len(entries)} open rows, each with its Sylow 2-quotient, `m = √(k − λ)`, `w = v₂(m) < t` and
`2^(w+1) ∣ s`, checked by `SyTwoCert.Kills` in chunks of {CHUNK}, one `decide +kernel` each;
generated by `solver/sylowtworows.py`.
-/

@[expose] public section

namespace SignedDifferenceSets

{chr(10).join(chunks)}
end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
    print(len(entries), "rows")


if __name__ == "__main__":
    main()
