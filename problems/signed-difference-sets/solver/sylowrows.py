"""Rows killed by C22's divisibility form (`not_hasSDS_of_sylow`), as data for the Lean rows.

`sylowrows.py`: writes lean/SignedDifferenceSets/SylowRows.lean (chunks of CHUNK rows, one
`decide +kernel` each) and prints the rows. For each open row of instances.csv and prime p
dividing gcd(v, n), the quotient
`Grp ds` keeps the p-part of each factor (dᵢ = p^v_p(mᵢ), `quot`), t = v_p(v), J = max v_p(mᵢ),
r = p^(J−1), φ = (p − 1) r, e = v_p(n), q the largest with 2(qφ + 1) ≤ eφ; the row dies when
p^min(t, q+1) ∤ s (s² = k + λ(v − 1)). Prints `id p r e q t s ds` per killed row (first prime that
kills). Standard library only; mirrors the Lean hypotheses.
"""
import csv
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "SylowRows.lean"
CHUNK = 50
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
OPEN = "open"


def vp(x, p):
    x, e = abs(x), 0
    while x and x % p == 0:
        x //= p
        e += 1
    return e


def primes_of(n):
    n, out, q = abs(n), [], 2
    while q * q <= n:
        if n % q == 0:
            out.append(q)
            while n % q == 0:
                n //= q
        q += 1
    if n > 1:
        out.append(n)
    return out


def cert(v, k, lam, ms):
    n = k - lam
    S = k + lam * (v - 1)
    if n == 0 or S < 0 or math.isqrt(S) ** 2 != S:
        return None
    s = math.isqrt(S)
    for p in primes_of(math.gcd(v, n)):
        ds = [p ** vp(m, p) for m in ms]
        J = max(vp(m, p) for m in ms)
        if J == 0:
            continue
        r = p ** (J - 1)
        phi = (p - 1) * r
        e, t = vp(n, p), vp(v, p)
        q = (e * phi - 2) // (2 * phi) if e * phi >= 2 else -1
        if q < 0:
            continue
        if s % p ** min(t, q + 1):
            return p, r, e, q, t, s, ds
    return None


def main():
    out = []
    for row in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if row["status"] != OPEN:
            continue
        m = KEY.fullmatch(row["key"])
        v, k, lam = map(int, m.groups()[:3])
        ms = [int(x) for x in m.group(4).split(",")]
        c = cert(v, k, lam, ms)
        if c:
            out.append((row["id"], *c, ms, k, lam))
    entries = []
    for nid, p, r, e, q, t, s, ds, ms, k, lam in out:
        lam_lean = f"({lam})" if lam < 0 else str(lam)
        entries.append(f"  (⟨{nid[1:]}, [{', '.join(map(str, ms))}], {k}, {lam_lean}⟩,\n"
                       f"    ⟨{p}, {r}, {e}, {q}, {t}, {s}, [{', '.join(map(str, ds))}]⟩)")
        print(nid, p, r, e, q, t, s, ",".join(map(str, ds)))
    chunks = []
    for i in range(0, len(entries), CHUNK):
        j = i // CHUNK + 1
        body = ",\n".join(entries[i: i + CHUNK])
        chunks.append(f"""/-- Rows and certificates, chunk {j}. -/
def sylowRows{j} : List (Row × SyCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem sylowRows{j}_kill : ∀ x ∈ sylowRows{j}, x.2.Kills x.1 := by decide +kernel

/-- No row of chunk {j} has an SDS. -/
theorem sylowRows{j}_not_hasSDS {{x : Row × SyCert}} (hx : x ∈ sylowRows{j})
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  SyCert.not_hasSDS (sylowRows{j}_kill x hx) inst
""")
    OUT.write_text(f"""module

public import SignedDifferenceSets.SylowCheck

/-!
# Rows killed by C22 (divisibility form)

{len(entries)} open rows, each with a Sylow quotient and C22's exponents, checked by `SyCert.Kills`
in chunks of {CHUNK}, one `decide +kernel` each; generated by `solver/sylowrows.py`.
-/

@[expose] public section

namespace SignedDifferenceSets

{chr(10).join(chunks)}
end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
    print(len(out), "rows", flush=True)


if __name__ == "__main__":
    main()
