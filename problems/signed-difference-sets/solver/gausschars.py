"""Rows killed by C19 (Gaussian characters on a quotient of exponent 4), written as Lean.

`gausschars.py [<exclude.tsv> ...]`: for each open row of instances.csv (minus the IDs in the given
files), tries the componentwise quotients d_i ∈ {1, 2, 4}, d_i | m_i, |H| ≤ 64, and keeps the first
that passes Lean's `GaussKills`; writes lean/SignedDifferenceSets/GaussCharsRows.lean (one
`decide +kernel`). Standard library only; mirrors `reachMod`, `gaussX` and `GaussKills` exactly.
"""
import csv
import itertools
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "GaussCharsRows.lean"
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
OPEN = "open"
MAX_ORDER = 64
CHUNK = 60


def reach(N, A, a, S):
    for _ in range(a):
        S = {(r + x) % N for r in S for x in A}
    return S


def gauss_x(n, m):
    return [x for x in range(-m, m + 1) if any(x * x + y * y == n for y in range(m + 1))]


def gauss_kills(N, m, s):
    X2 = [2 * x for x in gauss_x(m * m, m)]
    for sp in (s, -s):
        for R in range(1, N + 1):
            if (N - R) % 2:
                continue
            if 0 in reach(N, X2, (N - R) // 2, reach(N, [m, -m], R - 1, {sp % N})):
                return False
    return True


def cert(v, k, lam, ms):
    n, S = k - lam, k + lam * (v - 1)
    if n <= 0 or S < 0 or math.isqrt(n) ** 2 != n or math.isqrt(S) ** 2 != S:
        return None
    m, s = math.isqrt(n), math.isqrt(S)
    choices = [[d for d in (1, 2, 4) if x % d == 0] for x in ms]
    for ds in sorted(itertools.product(*choices), key=math.prod):
        N = math.prod(ds)
        if 4 in ds and N <= MAX_ORDER and gauss_kills(N, m, s):
            return list(ds), m, s
    return None


def main(excludes):
    skip = set()
    for f in excludes:
        skip |= {l.split("\t")[0] for l in open(f, encoding="utf-8") if l.strip()}
    entries = []
    for r in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if r["status"] != OPEN or r["id"] in skip:
            continue
        mm = KEY.fullmatch(r["key"])
        v, k, lam = map(int, mm.groups()[:3])
        ms = [int(x) for x in mm.group(4).split(",")]
        c = cert(v, k, lam, ms)
        if c:
            ds, m, s = c
            entries.append(f"  (⟨{r['id'][1:]}, [{', '.join(map(str, ms))}], {k}, {lam}⟩, "
                           f"⟨[{', '.join(map(str, ds))}], {m}, {s}⟩)")
    chunks = []
    for i in range(0, len(entries), CHUNK):
        j = i // CHUNK + 1
        body = ",\n".join(entries[i: i + CHUNK])
        chunks.append(f"""/-- Rows and certificates, chunk {j}. -/
def gaussCharsRows{j} : List (Row × GcCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem gaussCharsRows{j}_kill : ∀ x ∈ gaussCharsRows{j}, x.2.Kills x.1 := by decide +kernel

/-- No row of chunk {j} has an SDS. -/
theorem gaussCharsRows{j}_not_hasSDS {{x : Row × GcCert}} (hx : x ∈ gaussCharsRows{j})
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  GcCert.not_hasSDS (gaussCharsRows{j}_kill x hx) inst
""")
    OUT.write_text(f"""module

public import SignedDifferenceSets.GaussChars
public import SignedDifferenceSets.SelfConjugacyCheck

/-!
# Rows killed by C19

A certificate is a quotient `Grp ds` with every `dᵢ ∣ 4` (so `4h = 0`), `m = √(k − λ)` and the
sign sum `s` (C1); `GcCert.Kills` checks it and `GaussKills`. {len(entries)} open rows, generated by
`solver/gausschars.py`, checked in chunks of {CHUNK}, one `decide +kernel` each.
-/

@[expose] public section

namespace SignedDifferenceSets

/-- A C19 certificate: the quotient, `√(k − λ)` and the sign sum. -/
structure GcCert where
  ds : List ℕ
  m : ℤ
  s : ℤ
  deriving DecidableEq

/-- The row's arithmetic and C19's kill condition on `Grp ds`. -/
def GcCert.Kills (r : Row) (c : GcCert) : Prop :=
  (∀ m ∈ r.ms, 0 < m) ∧ Dvds c.ds r.ms ∧ (∀ d ∈ c.ds, d ∣ 4) ∧ c.m ^ 2 = r.k - r.lam ∧
    c.s ^ 2 = r.k + r.lam * ((r.ms.prod : ℤ) - 1) ∧ GaussKills c.ds.prod c.m c.s

instance GcCert.instDecidableKills (r : Row) (c : GcCert) : Decidable (c.Kills r) := by
  unfold GcCert.Kills; infer_instance

/-- A row C19 kills has no SDS, whatever `Fintype` instance its group carries. -/
theorem GcCert.not_hasSDS {{r : Row}} {{c : GcCert}} (h : c.Kills r) (inst : Fintype (Grp r.ms)) :
    ¬ @HasSDS (Grp r.ms) _ inst r.k r.lam := by
  obtain ⟨hms, hdv, h4, hm, hs, hk⟩ := h
  let _ : Fintype (Grp c.ds) := Grp.fintype c.ds (Dvds.pos _ _ hdv hms)
  refine not_hasSDS_of_gaussChars (quot_surjective r.ms c.ds hdv)
    (fun x => Grp.nsmul_eq_zero c.ds h4 x) hm (s := c.s) ?_ ?_
  · rw [hs, Grp.card_eq]
  · rwa [Grp.card_eq]

{chr(10).join(chunks)}
end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
    print(len(entries), "rows")


if __name__ == "__main__":
    main(sys.argv[1:])
