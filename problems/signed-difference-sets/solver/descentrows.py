"""Rows killed by C26 (Ma's lemma at equality, parity of the halved SDS), written as Lean.

`descentrows.py [skip.tsv ...]`: for each open row of instances.csv whose group is C_{2^j} x K with K odd, 2 self-conjugate
mod exp K (so c = 1), v2(k - lambda) in {2, 3} and s = sqrt(k + lambda (v - 1)), the row dies when neither
2s - (k + lambda) nor -2s - (k + lambda) is divisible by 8. Rows listed in the skip files (pending batches of other rules)
are left out. Writes lean/SignedDifferenceSets/DescentRows.lean, one `decide +kernel` per chunk. Mirrors
`DescentCert.Kills`; the map and its preimages are built as in `marows.py`. Standard library only.
"""
import csv
import math
import sys
from pathlib import Path

from marows import KEY, OPEN, conj_exp, crt, lst, map_ok, surj_cert, vp

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lean" / "SignedDifferenceSets" / "DescentRows.lean"
CHUNK = 40
PAIRS = {2 ** a for a in range(8)}  # r with (2, r) in MaRows.maPairs


def cert(ms, k, lam):
    v, n = math.prod(ms), k - lam
    if n <= 0 or vp(n, 2) not in (2, 3):
        return None
    even = [t for t, m in enumerate(ms) if m % 2 == 0]
    if len(even) != 1:
        return None
    s_ix = even[0]
    pj = 2 ** vp(ms[s_ix], 2)
    r = pj // 2
    if r not in PAIRS:
        return None
    kap = [m // 2 ** vp(m, 2) for m in ms]
    src = [t for t, x in enumerate(kap) if x > 1]
    ks = [kap[t] for t in src] or [1]
    src = src or [s_ix]
    i = conj_exp(2, math.lcm(*ks))
    if i is None:
        return None
    S = k + lam * (v - 1)
    s = math.isqrt(S) if S >= 0 else -1
    if s < 0 or s * s != S:
        return None
    if (2 * s - (k + lam)) % 8 == 0 or (-2 * s - (k + lam)) % 8 == 0:
        return None
    A = [[0] * s_ix + [1]] + [[0] * t + [1] for t in src]
    P = [[0] * s_ix + [crt(1, pj, 0, kap[s_ix])]]
    for t, d in zip(src, ks):
        P.append([0] * t + [crt(1, d, 0, pj) if t == s_ix else 1 % d])
    ds = [r * 2] + ks
    ok = (r > 0 and i > 0 and all(m > 0 for m in ms) and all((2 ** i + 1) % d == 0 for d in ks)
          and map_ok(ms, ds, A) and surj_cert(ms, ds, A, P) and v == r * 2 * math.prod(ks)
          and n % 4 == 0)
    assert ok, (ms, k, lam)
    return r, i, s, ks, A, P


def main():
    skip = set()
    for f in sys.argv[1:]:
        skip |= {line.split("\t")[0] for line in open(f, encoding="utf-8") if line.strip()}
    entries = []
    for row in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if row["status"] != OPEN or row["id"] in skip:
            continue
        m = KEY.fullmatch(row["key"])
        v, k, lam = map(int, m.groups()[:3])
        ms = [int(x) for x in m.group(4).split(",")]
        c = cert(ms, k, lam)
        if c:
            r, i, s, ks, A, P = c
            lam_l = f"({lam})" if lam < 0 else str(lam)
            entries.append((row["id"], f"  (⟨{row['id'][1:]}, {lst(ms)}, {k}, {lam_l}⟩,\n"
                                       f"    ⟨{r}, {i}, {s}, {lst(ks)},\n"
                                       f"      {lst([lst(a) for a in A])},\n"
                                       f"      {lst([lst(q) for q in P])}⟩)"))
    chunks = []
    for c0 in range(0, len(entries), CHUNK):
        j = c0 // CHUNK + 1
        body = ",\n".join(e for _, e in entries[c0: c0 + CHUNK])
        chunks.append(f"""/-- Rows and certificates, chunk {j}. -/
def descentRows{j} : List (Row × DescentCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem descentRows{j}_kill : ∀ x ∈ descentRows{j}, x.2.Kills x.1 := by decide +kernel

/-- No row of chunk {j} has an SDS. -/
theorem descentRows{j}_not_hasSDS {{x : Row × DescentCert}} (hx : x ∈ descentRows{j})
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  DescentCert.not_hasSDS (descentRows{j}_kill x hx) inst
""")
    OUT.write_text(f"""module

public import SignedDifferenceSets.MaDescent

/-!
# Rows killed by C26 (Ma's lemma at equality)

{len(entries)} open rows on `C_(2^j) × K` (`c = 1`, `v₂(k − λ) ∈ {{2, 3}}`) whose halved SDS
fails parity, checked by `DescentCert.Kills` in chunks of {CHUNK}, one `decide +kernel` each;
generated by `solver/descentrows.py`.
-/

@[expose] public section

namespace SignedDifferenceSets

{chr(10).join(chunks)}
end SignedDifferenceSets
""", encoding="utf-8", newline="\n")
    Path(ROOT / "scratch" / "c26" / "rows.txt").write_text("".join(i + "\n" for i, _ in entries), encoding="utf-8")
    print(len(entries), "rows")


if __name__ == "__main__":
    main()
